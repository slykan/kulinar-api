<p>
    „Žlica soli", „šalica brašna", „15 deka šećera" — domaći recepti puni su mjera koje svatko shvati malo
    drukčije. Evo kako ih pretvoriti u grame i mililitre, i kako jednostavno preračunati recept za više ili
    manje osoba.
</p>

