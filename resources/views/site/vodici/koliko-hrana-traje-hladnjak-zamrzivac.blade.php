<p>
    Na −18 °C hrana ostaje sigurna i nakon tih rokova, ali gubi okus i teksturu i dobiva „opekline od smrzavanja"
    (suhe, sive mrlje). Zato su rokovi u tablici rokovi <strong>kvalitete</strong>.
</p>

<h2>Odmrzavanje</h2>
<ol>
    <li><strong>U hladnjaku</strong> — najsigurnije. Računaj oko 24 sata za svaka 2 kg mesa. Meso odmrznuto u hladnjaku može se, ako treba, ponovno zamrznuti.</li>
    <li><strong>U hladnoj vodi</strong> — meso u zatvorenoj vrećici, vodu mijenjaj svakih 30 minuta. Nakon toga ga odmah kuhaj.</li>
    <li><strong>U mikrovalnoj</strong> — samo ako ćeš ga odmah kuhati, jer se dijelovi mesa počnu peći.</li>
</ol>
<div class="warn">
    Ne odmrzavaj meso na kuhinjskom stolu. Vanjski sloj satima stoji na sobnoj temperaturi dok je sredina još
    smrznuta, a upravo tada se bakterije najbrže množe.
</div>

<h2>Savjeti za kuhana jela</h2>
<ul>
    <li><strong>Ohladi brzo</strong> — velike lonce variva podijeli u manje posude da se brže ohlade, i u hladnjak ih stavi unutar 2 sata od kuhanja.</li>
    <li><strong>Podgrijavaj temeljito</strong> — do vrenja, odnosno do 74 °C u sredini. Vidi <a href="/vodici/temperatura-pecenja-mesa">temperature pečenja mesa</a>.</li>
    <li><strong>Označi posude</strong> — naziv i datum na poklopcu zamrznute hrane uštedi puno pogađanja.</li>
    <li><strong>Zamrzavaj u porcijama</strong> — sarma, gulaš ili grah u porcijama za jedan obrok odmrzavaju se brže i ne baca se ništa.</li>
</ul>
<p>
    Ne oslanjaj se samo na miris: neke bakterije koje uzrokuju trovanje ne mijenjaju miris ni izgled hrane. U
    nedoumici — baci.
</p>

