<p>Šalice nisu standardizirane — ako recept ne kaže koliko ima, najsigurnije je mjeriti istom šalicom za sve sastojke.</p>

<h2>Koliko je grama u žlici?</h2>
<p>Ovisi o sastojku, jer različiti sastojci imaju različitu gustoću. Okvirno, za <strong>ravnu</strong> žlicu:</p>
