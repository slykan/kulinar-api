<p>
    Prosinac je mjesec u kojem se kuha najviše i najsvečanije. Advent počinje kolačima i kuhanim vinom, Badnjak je posni dan s ribom,
    Božić je dan pečenke i bogatog stola, a Stara godina završava hladnim predjelima i salatama koje se mogu pripremiti ranije.
    Ovdje je jelovnik za svaki od tih dana i plan što napraviti unaprijed, da i ti uživaš u blagdanima.
</p>

<h2>Advent: kolači i kuhano vino</h2>
<p>
    Kolači koji dobro podnose stajanje peku se već početkom prosinca: <a href="/recepti/medenjaci-bozicni">medenjaci</a> nakon nekoliko dana
    u limenci postaju mekši i mirisniji, a <a href="/recepti/vanilin-kiflice">vanilin kiflice</a> u zatvorenoj kutiji traju dva do tri tjedna.
    Za hladne večeri i adventske posjete tu je <a href="/recepti/kuhano-vino-crno">kuhano vino</a>, koje se pripremi za deset minuta.
</p>

<h2>Badnjak: posni stol</h2>
<p>
    Na Badnjak se tradicionalno ne jede meso. Na kontinentu je to najčešće riba (šaran, som ili štuka) i grah, a u Dalmaciji i Istri
    <a href="/recepti/bakalar-na-bijelo">bakalar na bijelo</a> ili na crveno. Bakalar se počinje namakati dva do tri dana ranije,
    pa ga stavi u vodu najkasnije 21. prosinca.
</p>
<ul>
    <li>Predjelo: bakalar na bijelo s prepečenim kruhom ili palentom</li>
    <li>Glavno jelo: pečena ili pohana riba, krumpir salata, blitva</li>
    <li>Kolač: orahnjača, makovnjača ili fritule</li>
</ul>

<h2>Božić: pečenka i mlinci</h2>
<p>
    Na božićnom stolu najčešće je <a href="/recepti/purica-s-mlincima">purica s mlincima</a>, a u mnogim kućama i odojak, janjetina ili
    <a href="/recepti/sarma-od-kiselog-kupusa">sarma</a>, koja je dan nakon kuhanja još bolja. Od kolača se uz orahnjaču peku i
    sitni kolačići iz adventa.
</p>
<ul>
    <li>Juha: goveđa ili kokošja juha s rezancima</li>
    <li>Glavno jelo: purica s mlincima ili pečenka, uz kiseli kupus ili salatu od cikle</li>
    <li>Kolač: <a href="/recepti/orahnjaca-bozicna">orahnjača</a> i sitni kolači</li>
</ul>

<h2>Stara godina: hladni stol</h2>
<p>
    Za doček je najpraktičniji hladni stol koji se priprema poslijepodne, a jede cijelu noć. Neizostavna je
    <a href="/recepti/francuska-salata">francuska salata</a>, uz narezke, sireve, punjena jaja i slane štapiće. Iza ponoći dobro dođe
    nešto toplo: sarma, kobasice ili gulaš.
</p>

