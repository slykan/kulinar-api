<p>
    Topljenje masti i čvaraka obično traje dok traje i ostatak kolinja — kotao se pristavi poslijepodne i miješa se dok se ostali bave
    krvavicama i švarglom. Dobra mast je bijela, bez mirisa i traje cijelu godinu, a dobri čvarci su zlatni, hrskavi izvana i sočni iznutra.
</p>

<h2>Koja slanina za što</h2>
<ul>
    <li><strong>Leđna slanina bez kože</strong> daje najviše masti (oko 70 %) i sitnije, hrskave čvarke.</li>
    <li><strong>Slanina s malo mesa</strong> (s potrbušine i obrezaka) daje manje masti, ali najbolje čvarke.</li>
    <li><strong>Salo</strong> (unutarnja mast oko bubrega) daje najbjelju i najfiniju mast, a čvarci su sitni. Najbolje ga je topiti posebno ako želiš mast za kolače.</li>
</ul>
<p>Koliko masti, čvaraka i staklenki možeš očekivati izračunaj u <a href="/kalkulatori/mast-cvarci">kalkulatoru masti i čvaraka</a>.</p>

<h2>Postupak</h2>
<ol>
    <li><strong>Rezanje:</strong> slaninu nareži na kocke od 2–3 cm, što ujednačenije, da se prže jednako. Ako ostavljaš kožu, kocke neka budu manje.</li>
    <li><strong>Voda:</strong> u kotao ulij oko 1 dl vode na kg slanine. Na početku sprječava zagorijevanje, a kasnije potpuno ispari.</li>
    <li><strong>Topljenje:</strong> vatra srednja, a miješanje često, drvenom lopaticom, do samog dna. Prvo ključa voda, a onda se slanina počne pržiti u vlastitoj masti.</li>
    <li><strong>Kraj:</strong> kad čvarci dobiju zlatnu boju i počnu tonuti, a mast postane bistra i prestane pjeniti, gotovo je. Neki dodaju malo mlijeka (1 dl na 5 kg) za ljepšu boju — pripazi, jer zapjeni.</li>
    <li><strong>Cijeđenje:</strong> čvarke izvadi cjediljkom, a mast procijedi kroz gazu ili sito u staklenke.</li>
    <li><strong>Prešanje:</strong> vruće čvarke stisni u preši za čvarke da izađe ostatak masti. Što ih jače prešaš, to su suši i dulje traju.</li>
    <li><strong>Soljenje:</strong> posoli ih dok su topli, oko 15–20 g soli na kg čvaraka.</li>
</ol>

<div class="warn">
    Vruća mast prži jače od ulja i teško se gasi. Kotao neka stoji stabilno, djeca i psi podalje, a mokro posuđe ne smije u blizinu.
    Ako se mast zapali, poklopi je poklopcem ili mokrom krpom — <strong>nikad ne gasi vodom</strong>.
</div>

<h2>Spremanje masti</h2>
<ul>
    <li>Staklenke trebaju biti čiste i potpuno suhe. Mast ulijevaj dok je topla, ali ne kipuća, da staklenke ne puknu.</li>
    <li>Zatvori ih kad se mast ohladi i stvrdne. Na hladnom i tamnom mjestu traje 6–12 mjeseci.</li>
    <li>Ako mast miriše užeglo ili ima žutu boju, nije bila dovoljno procijeđena ili je u njoj ostalo vode.</li>
</ul>

<h2>Česta pitanja</h2>
<h3>Zašto mi je mast žuta?</h3>
<p>Prepržena je ili je topljena na prejakoj vatri. Bijela mast se dobiva laganim topljenjem, posebno od sala.</p>
<h3>Zašto su čvarci tvrdi kao kamen?</h3>
<p>Prepečeni su ili prejako prešani. Makni ih s vatre čim dobiju zlatnu boju jer se još prže u vrućoj masti.</p>
