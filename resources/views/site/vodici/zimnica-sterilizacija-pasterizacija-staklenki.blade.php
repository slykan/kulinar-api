<p>
    Ajvar, pekmez, turšija, kompot, pelati — zimnica je najbolji način da ljeto potraje do proljeća. Ali staklenka
    koja nije dobro pripremljena i zatvorena može se pokvariti, a u najgorem slučaju biti i opasna. Evo kako
    pravilno pripremiti staklenke i kada je dovoljna pasterizacija u vodenoj kupelji.
</p>

<h2>Kisela i nekisela zimnica</h2>
<p>
    Najvažnija podjela je prema <strong>kiselosti</strong>. Bakterija <em>Clostridium botulinum</em>, koja stvara opasni
    botulinski toksin, ne razvija se u kiseloj sredini (pH ispod 4,6), ali može preživjeti kuhanje na 100 °C u
    nekiseloj hrani zatvorenoj bez zraka.
</p>
<table class="t">
    <tr><th>Vrsta</th><th>Primjeri</th><th>Postupak</th></tr>
    <tr><td>Kisela</td><td>voće, pekmez, džem, kompot, turšija u octu, kiseli krastavci</td><td>vodena kupelj (100 °C) je dovoljna</td></tr>
    <tr><td>Rajčica</td><td>pelati, sok, umak</td><td>vodena kupelj uz dodatak kiseline (limunov sok ili limunska kiselina)</td></tr>
    <tr><td>Nekisela</td><td>grah, mahune, grašak, kukuruz, gljive, meso u staklenci</td><td>samo autoklav (tlak, 116–121 °C) — ili zamrzavanje</td></tr>
</table>
<div class="warn">
    Nekiselo povrće (mahune, grašak, gljive) bez octa nije sigurno konzervirati samo kuhanjem staklenki u loncu.
    Takvo povrće radije zamrzni, ili ga ukiseli octom prema provjerenom receptu.
</div>

<h2>Priprema staklenki</h2>
<ol>
    <li>Pregledaj staklenke — bez napuklina i okrhnutih rubova. Poklopci moraju biti neoštećeni, s očuvanom gumicom; nove poklopce je najbolje kupiti svake sezone.</li>
    <li>Operi ih u vrućoj vodi s deterdžentom i dobro isperi.</li>
    <li><strong>Steriliziraj</strong> ih: u pećnici na 120 °C oko 20 minuta (staklenke bez poklopaca) ili kuhanjem u loncu vode 10 minuta. Poklopce prokuhaj nekoliko minuta.</li>
    <li>Staklenke punjenje čekaju vruće — vruća masa u hladnoj staklenci može je razbiti.</li>
</ol>

<h2>Punjenje i zatvaranje</h2>
<ul>
    <li>Ostavi <strong>prostor do vrha</strong>: oko 0,5–1 cm za pekmez i džem, 1–2 cm za povrće u salamuri i kompote.</li>
    <li>Čistom, vlažnom krpom obriši rub staklenke — i mala mrlja pekmeza na rubu sprječava da poklopac dobro brtvi.</li>
    <li>Zatvori poklopac čvrsto, ali bez sile.</li>
</ul>

<h2>Pasterizacija u vodenoj kupelji</h2>
<ol>
    <li>Na dno velikog lonca stavi krpu ili rešetku, da staklenke ne stoje izravno na dnu.</li>
    <li>Složi staklenke tako da se ne dodiruju i ulij toplu vodu da ih prekrije barem 2–3 cm.</li>
    <li>Zakuhaj i od trenutka vrenja računaj vrijeme: za staklenke do 0,7 l najčešće 10–20 minuta za pekmez, džem i turšiju, a dulje za kompote, rajčicu i veće staklenke — drži se vremena iz recepta.</li>
    <li>Staklenke izvadi i ostavi ih da se polako ohlade na krpi, daleko od propuha, do sljedećeg dana.</li>
</ol>

<h2>Je li staklenka dobro zatvorena</h2>
<p>
    Kad se ohladi, sredina poklopca mora biti <strong>uvučena</strong> i ne smije „klikati" kad je pritisneš. Ako se
    poklopac ulegne i vrati, staklenka nije zatvorena — stavi je u hladnjak i iskoristi u nekoliko dana.
</p>

<h2>Čuvanje i kada baciti</h2>
<ul>
    <li>Zimnicu čuvaj na tamnom i hladnom mjestu (smočnica, podrum), a otvorenu staklenku u hladnjaku.</li>
    <li>Na staklenku napiši sadržaj i godinu. Najbolja je kroz godinu dana.</li>
    <li><strong>Baci</strong> staklenku ako je poklopac napuhnut, ako sadržaj šišti, pjeni se ili curi, ako ima plijesan ili neobičan miris. Takav sadržaj ne kušaj.</li>
</ul>
