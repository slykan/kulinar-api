    nekoliko eura i najbolja je investicija za suho meso.
</p>

<h2>Kako znati da je gotovo</h2>
<ul>
    <li><strong>Gubitak težine</strong> — najpouzdaniji znak. Kobasice trebaju izgubiti 30–35 %, kulen 35–40 %, šunka 30–35 %. Izračunaj u <a href="/kalkulatori/susenje">kalkulatoru sušenja</a>.</li>
    <li><strong>Čvrstoća</strong> — komad je čvrst cijelom dužinom, ne samo izvana.</li>
    <li><strong>Presjek</strong> — ujednačene boje od kore do sredine, bez sivog ili mokrog središta.</li>
</ul>

<h2>Zatvorena kora</h2>
<p>
    Ako je zrak presuh, pretopao ili ima propuha, površina se osuši prebrzo i stvrdne. Ta kora zatvori izlaz vodi iz sredine, pa
    kobasica ostane mekana i vlažna iznutra i može se pokvariti. Znakovi: tvrda, naborana kora i mekana sredina, kobasica gubi težinu
    sve sporije iako je još mekana.
</p>
<p>
    <strong>Rješenje:</strong> premjesti meso na hladnije i vlažnije mjesto (podrum) na 1–2 tjedna da se vlaga izjednači, pa nastavi
    sporije. Neki kobasice kratko zamotaju u vlažnu krpu ili najlon na dan-dva.
</p>

<h2>Plijesan: dobra i loša</h2>
<ul>
    <li><strong>Bijela, sitna, praškasta plijesan</strong> je normalna i čak poželjna na kulenu i pršutu. Štiti meso i pomaže zrenju. Može se obrisati krpom namočenom u ocat ili ostaviti.</li>
    <li><strong>Zelena ili plavozelena</strong> plijesan obično je površinska. Obriši je krpom s octom ili jakom rakijom i smanji vlagu u prostoriji.</li>
    <li><strong>Crna, žuta, crvena ili dlakava plijesan</strong> i plijesan koja ulazi u meso znak su da nešto nije u redu. Komad treba baciti ili barem duboko odrezati zahvaćeni dio, a ostalo meso pregledati.</li>
</ul>
<div class="warn">
    Bacaj meso koje ima ljepljivu, sluzavu površinu, kiselo-trul miris, zelenkastu ili sivu boju u sredini ili šupljine s tekućinom.
    Kod suhog mesa nema „probat ću pa ću vidjeti”.
</div>

<h2>Čuvanje gotovog suhog mesa</h2>
<ul>
    <li><strong>Obješeno</strong> u hladnom, prozračnom podrumu — kobasice i kulen se nastavljaju polako sušiti i postaju tvrđi.</li>
    <li><strong>Vakumirano u hladnjaku</strong> — zaustavlja sušenje, meso ostaje mekano mjesecima. Najbolji način za kobasice koje su „taman”.</li>
    <li><strong>Zakopano u mast</strong> ili pepeo — stari načini koji i dalje rade za kobasice i suha rebra.</li>
    <li><strong>Zamrzavanje</strong> — moguće, ali suho meso nakon odmrzavanja gubi na teksturi.</li>
</ul>
