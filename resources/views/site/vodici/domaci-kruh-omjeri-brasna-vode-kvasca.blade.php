</p>

<h2>Hidratacija: koliko vode</h2>
<p>
    Postotak vode zove se hidratacija i najviše utječe na kruh:
</p>
<ul>
    <li><strong>60–65 %</strong> — tijesto se lako oblikuje, sredina je gušća. Za početnike i kalupe.</li>
    <li><strong>68–72 %</strong> — mekša, rupičastija sredina, tijesto ljepljivije.</li>
    <li><strong>75 % i više</strong> — velike rupe (ciabatta, kruh s kiselim tijestom), tijesto se teško oblikuje bez iskustva.</li>
</ul>
<p>
    Integralno i raženo brašno upijaju više vode od bijelog, pa im dodaj 5–10 % više vode.
</p>

<h2>Postupak</h2>
<ol>
    <li><strong>Miješanje:</strong> u brašno umiješaj kvasac, dodaj mlaku vodu (oko 30 °C) i promiješaj dok ne nestane suhog brašna. Pusti 20 minuta da odmori, pa dodaj sol.</li>
    <li><strong>Mijesenje:</strong> 8–10 minuta rukom ili 5–6 minuta mikserom, dok tijesto ne postane glatko i elastično. Tanki komad tijesta treba se rastegnuti u prozirnu opnu bez trganja.</li>
    <li><strong>Prvo dizanje:</strong> pokrij i ostavi na sobnoj temperaturi 1–1,5 sat, dok se ne udvostruči. Za bolji okus tijesto može dizati u hladnjaku preko noći, uz upola manje kvasca.</li>
    <li><strong>Oblikovanje:</strong> tijesto lagano istisni, oblikuj okruglicu ili štrucu, napni mu površinu i stavi u pobrašnjenu košaricu ili kalup.</li>
    <li><strong>Drugo dizanje:</strong> 40–60 minuta. Gotovo je kad se udubljenje od prsta polako, ali ne potpuno vrati.</li>
    <li><strong>Pečenje:</strong> pećnicu zagrij na 230–250 °C. Kruh zareži oštrim nožem i peci prvih 15 minuta s parom (posuda s vodom na dnu pećnice ili poklopljena teška posuda), zatim smanji na 210–220 °C i peci još 25–30 minuta.</li>
    <li><strong>Hlađenje:</strong> kruh je gotov kad je kora tamnozlatna, a kucanje po dnu daje šupalj zvuk. Ohladi ga na rešetki barem sat vremena prije rezanja — sredina se još dovršava.</li>
</ol>

<h2>Česte pogreške</h2>
<ul>
    <li><strong>Sol izravno na kvasac</strong> — sol usporava kvasac; dodaj je u brašno ili nakon odmora.</li>
    <li><strong>Prevruća voda</strong> — iznad oko 50 °C kvasac ugiba. Voda treba biti mlaka.</li>
    <li><strong>Previše brašna pri oblikovanju</strong> — mijenja omjer i daje suh kruh. Radije navlaži ruke.</li>
    <li><strong>Prekratko pečenje</strong> — blijeda kora i gnjecava sredina. Kruh peci dok ne dobije boju.</li>
    <li><strong>Rezanje vrućeg kruha</strong> — sredina se lijepi i djeluje nedopečeno.</li>
</ul>

<h2>Kiselo tijesto (kvasni ukvas)</h2>
<p>
    Umjesto kvasca kruh se može dići prirodnim kiselim tijestom — mješavinom brašna i vode u kojoj žive divlji
    kvasci i bakterije mliječne kiseline. Tipično se koristi 20 % aktivnog ukvasa u odnosu na brašno, a dizanje traje
    znatno dulje (6–12 sati). Kruh ima kiselkast okus, čvršću koru i dulje ostaje svjež.
</p>
