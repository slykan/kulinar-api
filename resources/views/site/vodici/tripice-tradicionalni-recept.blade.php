<p>
    Tripice ili fileki — jelo koje se ili voli ili ne podnosi. Oni koji ih vole znaju da sve ovisi o dvije
    stvari: dobro očišćenim i dovoljno dugo kuhanim tripicama te gustom, aromatičnom umaku.
</p>

<h2>Kakve tripice kupiti</h2>
<p>
    U trgovinama se najčešće prodaju <strong>očišćene i prethodno kuhane (blanširane)</strong> goveđe tripice —
    bijele su i bez jakog mirisa. One se kuhaju kraće. Sirove, neočišćene tripice zahtijevaju puno više rada i
    vremena, pa ih većina kupuje već pripremljene.
</p>

<h2>1. Čišćenje i kuhanje tripica</h2>
<ol>
    <li>Tripice dobro operi pod mlazom hladne vode, nekoliko puta, i ukloni ostatke masnoće.</li>
    <li>Stavi ih u lonac s hladnom vodom, zakuhaj i nakon par minuta vodu prospi — tako odlazi dio mirisa.</li>
    <li>Nalij svježu vodu, dodaj mrkvu, celer, peršin i lovor, pa kuhaj na laganoj vatri dok ne omekšaju.
        Prethodno kuhanim tripicama treba oko 1–1,5 sat, a sirovima i nekoliko sati.</li>
    <li>Tripice izvadi, ohladi i nareži na tanke rezance. Temeljac sačuvaj.</li>
</ol>
<div class="note">Tripice su gotove kad ih vilica lako probode i kad se rezanac lako prereže. Ako su „gumaste", kuhaj dalje.</div>

<h2>2. Umak</h2>
<p>Za 500 g tripica (oko 3 osobe) trebaš:</p>
<ul>
    <li>2 glavice luka, 2 češnja češnjaka</li>
    <li>100 g dimljene slanine i 100 g obične slanine</li>
    <li>žličicu koncentrata rajčice i žličicu slatke paprike</li>
    <li>žlicu brašna i 2 žlice krušnih mrvica za zgušnjavanje</li>
    <li>dodatak jelima, sol i tucanu ljutu papriku po ukusu</li>
    <li>oko 1,5 l temeljca od kuhanja tripica</li>
</ul>
<p>Za drugu količinu sve preračuna <a href="/kalkulatori/tripice">kalkulator tripica</a>.</p>
<ol>
    <li>Na slanini narezanoj na kockice popirjaj sitno nasjeckan luk dok ne omekša i dobije boju.</li>
    <li>Dodaj češnjak, pa lonac makni s vatre i umiješaj slatku papriku (da ne zagori i ne pogorči).</li>
    <li>Dodaj koncentrat rajčice i tripice, promiješaj i zalij temeljcem.</li>
    <li>Kuhaj poklopljeno na laganoj vatri 30–45 minuta da se okusi povežu.</li>
    <li>Brašno poprži na malo masnoće u zapršku, razrijedi s malo umaka i vrati u lonac; dodaj mrvice.</li>
    <li>Kuhaj još 10 minuta, posoli i dodaj tucanu papriku po ukusu.</li>
</ol>

<h2>Posluživanje</h2>
<p>
    Tripice se poslužuju vruće, posute naribanim tvrdim sirom (parmezan ili domaći tvrdi sir) i s kruhom za
    umakanje. Kao i većina varivo-jela, sutradan su još bolje.
</p>

<h2>Kako se riješiti mirisa</h2>
<ul>
    <li>Kupuj blanširane tripice i dobro ih isperi.</li>
    <li>Prvu vodu nakon zakuhavanja uvijek prospi.</li>
    <li>U vodu za kuhanje stavi korjenasto povrće i lovor; neki dodaju i malo octa.</li>
</ul>
