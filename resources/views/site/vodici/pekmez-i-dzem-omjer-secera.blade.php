<p>
    Pekmez, džem, marmelada — u svakodnevnom govoru isto, a zapravo se razlikuju po tome koliko se dugo kuhaju i koliko
    šećera imaju. Šećer nije samo slatkoća: on konzervira i pomaže da se voće zgusne. Ovo su osnovni omjeri i
    postupci.
</p>

