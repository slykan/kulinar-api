<p>
    Nakon soljenja i dimljenja slijedi najdulji dio posla: sušenje. Meso polako gubi vodu, sol se izjednačava od kore do sredine, a okus
    sazrijeva. Dobro sušenje je ravnoteža: ne presuho i ne prevlažno, ne pretoplo i bez propuha.
</p>

