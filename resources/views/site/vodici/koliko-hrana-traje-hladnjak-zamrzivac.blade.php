<p>
    Koliko dugo smije stajati kuhani grah u hladnjaku? Smije li se ponovno zamrznuti odmrznuto meso? Bacanje hrane
    je skupo, a pokvarena hrana opasna. Ovo su okvirni rokovi koje preporučuju agencije za sigurnost hrane i
    pravila koja vrijede u svakoj kuhinji.
</p>

<h2>Temperatura je najvažnija</h2>
<ul>
    <li><strong>Hladnjak:</strong> 4 °C ili manje. Mnogi hladnjaci su postavljeni na 6–8 °C — kupi jeftini termometar i provjeri.</li>
    <li><strong>Zamrzivač:</strong> −18 °C ili manje. Na toj temperaturi bakterije ne rastu, ali kvaliteta s vremenom pada.</li>
    <li><strong>Pravilo dva sata:</strong> pokvarljiva hrana (meso, kuhana jela, mliječni proizvodi) ne bi smjela stajati na sobnoj temperaturi dulje od 2 sata, a ljeti na vrućini od preko 30 °C ni 1 sat.</li>
</ul>

