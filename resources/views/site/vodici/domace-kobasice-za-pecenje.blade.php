<h2>4. Mljevenje i miješanje</h2>
<ol>
    <li>Meso i slaninu nareži na kocke koje stanu u grlo mašine.</li>
    <li>Sameljaj na rešetku od 8–10 mm (za finije kobasice dio smjese još jednom na 4–5 mm).</li>
    <li>Začine prvo izmiješaj u zdjelici, pa ih ravnomjerno pospi po mesu.</li>
    <li>Mijesi rukama 3–5 minuta, dok smjesa ne postane ljepljiva i ne počne se „vući". Ako je pregusta, dodaj malo ledene vode (do 5 % mase).</li>
</ol>

<h2>5. Crijeva i punjenje</h2>
<p>
    Za kobasice za pečenje koriste se <strong>svinjska tanka crijeva</strong> (promjer oko 28–32 mm). Soljena
    crijeva treba isprati iznutra i izvana i potopiti u mlaku vodu barem pola sata.
</p>
<ul>
    <li>Ne puni prečvrsto — kobasica se pri pečenju širi i puca.</li>
    <li>Mjehuriće zraka probuši iglom.</li>
    <li>Kobasice uvij u komade željene duljine (okreći naizmjence u suprotne smjerove).</li>
</ul>

<h2>6. Čuvanje</h2>
<p>
    Svježe kobasice su sirovo mljeveno meso: drže se u hladnjaku i <strong>potroše u 1–2 dana</strong>. Sve
    ostalo odmah zamrzni — vakuumirane ili dobro zamotane, u porcijama za jedan obrok. Zamrznute se drže
    nekoliko mjeseci; odmrzavaj ih u hladnjaku, ne na sobnoj temperaturi.
</p>

<div class="warn">
    Ovaj vodič je za <strong>svježe kobasice za pečenje</strong>. Kobasice koje se dime i suše (češnjovke, kulen)
    rade se drukčije: uz nitritnu sol u točno propisanoj količini i kontrolirane uvjete sušenja. Bez toga
    postoji rizik od opasnih bakterija — nemoj sušiti kobasice rađene po ovom omjeru.
</div>

<h2>Najčešće greške</h2>
<ul>
    <li><strong>Pretoplo meso</strong> — mrvičaste kobasice. Rješenje: sve ohladi, radi u turama.</li>
    <li><strong>Premalo masnoće</strong> — suhe kobasice. Ciljaj oko 30 %.</li>
    <li><strong>Sol „od oka"</strong> — računaj grame po kilogramu i probaj prije punjenja.</li>
    <li><strong>Prečvrsto punjenje</strong> — pucanje pri pečenju.</li>
</ul>
