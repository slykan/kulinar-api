<p>
    Za dobar domaći kruh ne treba poseban recept nego razumijevanje četiri sastojka: brašna, vode, kvasca i soli.
    Pekari ih računaju u <strong>pekarskim postocima</strong> — sve u odnosu na masu brašna. Kad to shvatiš, možeš
    peći bilo koju količinu i prilagoditi kruh po svom ukusu.
</p>

