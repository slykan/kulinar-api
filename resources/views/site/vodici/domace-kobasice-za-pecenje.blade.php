<p>
    Domaće kobasice za pečenje nisu komplicirane — ali razlika između „dobrih" i „onih koje svi traže" krije
    se u tri stvari: pravom omjeru mesa i masnoće, točnoj količini soli i temperaturi mesa dok ga radiš.
    Ovaj vodič prolazi kroz cijeli postupak, od mesnice do tave.
</p>

<h2>1. Meso i masnoća</h2>
<p>
    Za sočne kobasice najčešće se uzima svinjetina s oko <strong>70 % mesa i 30 % masnoće</strong>. Dobri su
    dijelovi vrat, plećka i obrezine, uz leđnu slaninu. Premršava smjesa (samo but ili kare) daje suhe i
    mrvičaste kobasice; previše masnoće — kobasice koje se u tavi „istope".
</p>
<ul>
    <li><strong>Svinjski vrat</strong> — sam po sebi ima gotovo idealan omjer mesa i masnoće.</li>
    <li><strong>Plećka + leđna slanina</strong> — klasična kombinacija; slanina se dodaje dok smjesa ne izgleda „prošarano".</li>
    <li>Dio svinjetine može se zamijeniti junetinom — kobasice su tada tamnije i čvršće.</li>
</ul>

<h2>2. Hladno, hladnije, najhladnije</h2>
<p>
    Meso i slanina moraju biti <strong>vrlo hladni</strong> — idealno tek iznad nule, čak i lagano zamrznuti na
    rubovima. Topla masnoća se pri mljevenju „razmaže", smjesa postaje pastozna i kobasice su nakon pečenja
    mrvičaste. Ohladi i dijelove mašine za mljevenje.
</p>

