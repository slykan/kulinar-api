<h2>Česta pitanja</h2>
<h3>Koliko purice po osobi?</h3>
<p>Računaj oko 500 g sirove purice s kostima po odrasloj osobi. Za šest osoba dovoljna je purica od 3 do 3,5 kg, a ako ostane, odlična je hladna u sendviču.</p>
<h3>Koliko dugo traju ostaci?</h3>
<p>Pečeno meso i francuska salata u hladnjaku traju 3 do 4 dana, a sarma i bakalar na bijelo 4 do 5 dana. Više o tome u vodiču <a href="/vodici/koliko-hrana-traje-hladnjak-zamrzivac">koliko hrana traje u hladnjaku i zamrzivaču</a>.</p>
<h3>Kako ispeći puricu da ne bude suha?</h3>
<p>Peci je pokrivenu na nižoj temperaturi, redovito je prelijevaj sokom i otkrij je tek na kraju. Najsigurnije je mjeriti termometrom. Prsa su gotova na 72 °C, a batak na 80 °C. Pogledaj i vodič o <a href="/vodici/temperatura-pecenja-mesa">temperaturi pečenja mesa</a>.</p>
