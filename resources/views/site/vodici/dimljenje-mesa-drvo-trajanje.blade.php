<p>Ovaj vodič je o hladnom dimljenju jer se tako dime proizvodi s kolinja.</p>

<h2>Koje drvo</h2>
<ul>
    <li><strong>Bukva</strong> — najčešći izbor, blag i ugodan dim i lijepa zlatna boja.</li>
    <li><strong>Grab, hrast, jasen</strong> — dobri, hrast daje jači okus i tamniju boju.</li>
    <li><strong>Voćke</strong> (šljiva, jabuka, trešnja) — blag, slatkast dim, često se miješaju s bukvom.</li>
    <li><strong>Piljevina i strugotine</strong> od tvrdog drva — tinjaju polako, bez plamena, pa su idealne za hladni dim.</li>
</ul>
<div class="warn">
    <strong>Nikako:</strong> crnogorica (bor, smreka, jela) zbog smole koja daje gorak okus i čađu, zatim lakirano, bojano ili
    impregnirano drvo, iverica i šperploča, te vlažno ili pljesnivo drvo.
</div>

<h2>Prije dimljenja</h2>
<ol>
    <li>Kobasice i kulen nakon punjenja objesi da se ocijede i prosuše 1–3 dana na hladnom. Površina mora biti suha na dodir, inače se dim „lijepi” i meso postane tamno i gorko.</li>
    <li>Šunku, pancetu i slaninu nakon soljenja operi mlakom vodom, ocijedi i prosuši 1–2 dana.</li>
    <li>Komadi u pušnici ne smiju se dodirivati, a najbliži bi trebali biti barem metar iznad vatre.</li>
</ol>

