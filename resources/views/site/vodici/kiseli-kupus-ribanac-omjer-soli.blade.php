<p>
    Domaći kiseli kupus nastaje fermentacijom: bakterije mliječne kiseline pretvaraju šećer iz kupusa u kiselinu
    koja ga konzervira. Ne treba ni ocat ni kuhanje — samo kupus, sol, vrijeme i pravilna temperatura. Ovo je
    postupak za <strong>ribanac</strong>, naribani kiseli kupus, koji se najlakše radi i u manjim količinama.
</p>

<h2>Koliko soli</h2>
<p>
    Ključni omjer je <strong>2–2,5 % soli</strong> u odnosu na masu očišćenog kupusa, odnosno 20–25 g soli na
    1 kg kupusa.
</p>
