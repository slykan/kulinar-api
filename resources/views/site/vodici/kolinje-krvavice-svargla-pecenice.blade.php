<h2>Švargla (tlačenka)</h2>
<p>
    Švargla je kuhano meso s glave, jezika, srca i kože, začinjeno i stisnuto u želudac ili debelo crijevo. Želatina iz kože i glave
    drži je na okupu kad se ohladi.
</p>
<ol>
    <li>Glavu, jezik, srce i kožu kuhaj u posoljenoj vodi s lovorom i paprom 2–3 sata, dok se meso ne odvaja od kosti.</li>
    <li>Meso skini s kostiju i nareži na kocke. Kožu sameljaj ili sitno nasjeckaj.</li>
    <li>Začini solju (oko 15 g po kg), paprom, češnjakom i slatkom paprikom, i dodaj malo procijeđene juhe od kuhanja.</li>
    <li>Napuni u očišćen želudac, zašij ili zaveži i kuhaj još 1–1,5 sat na laganoj vatri.</li>
    <li>Pritisni je daskom i utegom dok se hladi (tlači se — otud ime tlačenka). Nakon hlađenja može se kratko dimiti.</li>
</ol>
<p>Cijeli recept: <a href="/recepti/svargla-tlacenka">švargla (tlačenka)</a>.</p>

<h2>Pečenice</h2>
<p>
    Pečenice su svježe kobasice od finijeg mesa, a pojam se razlikuje od kraja do kraja. Negdje su to obične kobasice za pečenje, a
    negdje se pečenicom zove fino leđno meso (pečenica, „lungić”) koje se soli i suši. Za svježe pečenice nadjev se radi kao za
    <a href="/kalkulatori/kobasice">kobasice za pečenje</a>, uz više mesa i manje slanine (15–20 %) te malo bijelog vina.
</p>

