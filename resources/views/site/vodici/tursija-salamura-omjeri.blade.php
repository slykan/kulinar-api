<p>
    Turšija je jedan od najstarijih načina da se jesenski višak povrća sačuva do proljeća. Recepti se razlikuju
    od kuće do kuće, ali osnova je ista: povrće u kiselo-slanoj salamuri, u dobro zatvorenim teglama.
</p>

<h2>Salamura 1:3</h2>
<p>Najraširenija domaća salamura za miješanu turšiju radi se na <strong>litru octa</strong>:</p>
<table class="t">
    <tr><td>Alkoholni ocat (9 %)</td><td class="num">1 l</td></tr>
    <tr><td>Voda</td><td class="num">3 l</td></tr>
    <tr><td>Sol</td><td class="num">150 g</td></tr>
    <tr><td>Šećer</td><td class="num">250 g</td></tr>
    <tr><td>Papar u zrnu</td><td class="num">2 žlice</td></tr>
    <tr><td>Lovor</td><td class="num">3 lista</td></tr>
    <tr class="total"><td>Ukupno salamure</td><td class="num">oko 4 l</td></tr>
</table>
<p>Za veću ili manju količinu koristi <a href="/kalkulatori/tursija">kalkulator salamure za turšiju</a>.</p>
<p>
    Omjer 1:3 daje blagu, kiselo-slatku turšiju. Kiselija turšija radi se s manje vode (1:2), a ako je
    radiš s jabučnim octom od 5 %, smanji vodu otprilike na pola, jer je taj ocat slabiji.
</p>

<h2>Koje povrće</h2>
<ul>
    <li><strong>Paprika</strong> — babura, šiljasta ili rog; cijele (izbodene iglom) ili na trake.</li>
    <li><strong>Krastavci</strong> — manji, čvrsti, kornišoni ili salatni narezani na kolute.</li>
    <li><strong>Cvjetača</strong> — na manje cvjetove, kratko blanširana.</li>
    <li><strong>Mrkva</strong> — na kolutiće ili štapiće, za boju i hrskavost.</li>
    <li><strong>Luk</strong> — mali srebrnjak ili crveni luk na kolute.</li>
    <li><strong>Zelene rajčice i kupus</strong> — klasika za miješanu turšiju.</li>
</ul>
<p>Povrće mora biti svježe, čvrsto i bez trulih dijelova — turšija ne popravlja loše povrće.</p>

<h2>Postupak</h2>
<ol>
    <li>Tegle i poklopce operi u vrućoj vodi i osuši ili ih steriliziraj u pećnici.</li>
    <li>Povrće operi, nareži i čvrsto složi u tegle, ostavljajući 1–2 cm prostora do vrha.</li>
    <li>Ocat, vodu, sol i šećer zakuhaj dok se sol i šećer potpuno ne otope, pa dodaj papar i lovor.</li>
    <li>Povrće prelij vrućom salamurom tako da bude potpuno prekriveno.</li>
    <li>Tegle odmah zatvori.</li>
</ol>

<h2>Pasterizacija</h2>
<p>
    Za turšiju koja treba izdržati cijelu zimu tegle je dobro pasterizirati: složi ih u veliki lonac na krpu,
    nalij vodu do ramena tegli, zagrij vodu da bude vruća, ali da ne kipi (oko 80 °C), i drži tegle u njoj
    20–30 minuta, ovisno o veličini. Nakon toga ih ostavi da se polako ohlade.
</p>
<div class="note">
    Kad se ohlade, poklopci trebaju biti blago uvučeni prema unutra. Ako poklopac „klikće" kad ga pritisneš,
    tegla nije dobro zatvorena — tu turšiju čuvaj u hladnjaku i pojedi prvu.
</div>

<h2>Čuvanje i kad je gotova</h2>
<p>
    Turšija se čuva na tamnom i hladnom mjestu. Najbolja je nakon nekoliko tjedana, kad povrće upije salamuru.
    Otvorenu teglu drži u hladnjaku.
</p>
<div class="warn">
    Baci teglu ako je poklopac napuhnut, salamura mutna i pjenušava, ako je miris neugodan ili se vidi plijesan.
    Kod sumnje — ne kušaj.
</div>
