<h2>Kupljena (soljena) crijeva</h2>
<ol>
    <li>Odmotaj koliko ti treba i otresi sol. Ostatak odmah vrati u sol i u hladnjak.</li>
    <li>Namoči u mlakoj vodi: tanka 1–2 sata, debela i slijepa preko noći u hladnjaku.</li>
    <li>Svako crijevo natakni na slavinu i pusti mlaku vodu kroz njega. Tako se ispere sol iznutra i vide se rupe.</li>
    <li>Do punjenja ih drži u posudi s mlakom vodom, a pri punjenju ih natakni na lijevak mokra.</li>
</ol>
<p class="note">Soljena crijeva u hladnjaku traju godinu dana i više. Ne zamrzavaj ih, jer postaju krhka.</p>

<h2>Čišćenje domaćih crijeva</h2>
<p>Posao je neugodan, ali nije težak ako se radi odmah dok su crijeva topla, i ima puno vode.</p>
<ol>
    <li>Odvoji crijeva od maramice (masnog tkiva) pažljivo, prstima i nožem, da ih ne probušiš.</li>
    <li>Istisni sadržaj prema van, prstima od jednog kraja do drugog.</li>
    <li>Okreni crijevo naopako. Najlakše je tako da kraj preklopiš preko sebe i u nastali „džep” lijevaš vodu, pa se crijevo samo okreće.</li>
    <li>Ostruži unutarnju sluznicu tupom stranom noža ili drvenom daščicom na dasci, dok crijevo ne postane tanko i prozirno.</li>
    <li>Ispiri u više voda, pa namoči u vodi s octom ili limunom i malo soli nekoliko sati da nestane miris.</li>
    <li>Isperi još jednom, okreni natrag i provjeri na slavini da nema rupa.</li>
</ol>
<div class="warn">
    Domaća crijeva brzo se kvare. Koristi ih isti ili sljedeći dan, a čuvaj u soli u hladnjaku. Crijeva bolesne svinje ili ona koja imaju
    neugodan miris unatoč pranju ne koriste se.
</div>

<h2>Česta pitanja</h2>
<h3>Kako ukloniti miris s crijeva?</h3>
<p>Namakanjem u vodi s octom (1 dl na litru) ili limunovim sokom, uz nekoliko kriški limuna i lovor. Kupljena crijeva gotovo nemaju miris nakon ispiranja.</p>
<h3>Zašto crijeva pucaju?</h3>
<p>Presuha su, preoštro se nabijaju ili u stroju ima zraka. Drži ih mokrima i ne puni do kraja. Više u vodiču <a href="/vodici/domace-kobasice-za-pecenje">domaće kobasice za pečenje</a>.</p>
