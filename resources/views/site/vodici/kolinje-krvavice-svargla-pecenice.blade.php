<p>
    Kolinje je dan kada se od jedne svinje napravi zimnica za cijelu godinu: kobasice, krvavice, švargla, šunke, slanina, mast i čvarci.
    Ovdje je redoslijed poslova kakav se radi u većini kuća u kontinentalnoj Hrvatskoj, s naglaskom na ono što se radi
    <strong>isti dan</strong>: krvavice, švargla i pečenice. Za sušeno meso i kobasice pogledaj poveznice na kraju.
</p>

