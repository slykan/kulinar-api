<p>
    Dim daje kobasicama, slanini i šunki boju i okus, ali i štiti površinu mesa dok se suši. Kod kolinja se gotovo uvijek radi
    <strong>hladno dimljenje</strong>: meso visi u pušnici danima ili tjednima, uz slabu, tinjajuću vatru, i ne smije se zagrijati.
</p>

