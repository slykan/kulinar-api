<p>
    Je li piletina pečena do kraja? Je li svinjski vrat još ružičast iznutra smije biti? Boja mesa i bistri sok
    nisu pouzdan znak. Jedini siguran način je izmjeriti <strong>unutarnju temperaturu</strong> mesa kuhinjskim
    termometrom. Evo koje su temperature sigurne i kako mjeriti.
</p>

<h2>Sigurne unutarnje temperature</h2>
<table class="t">
    <tr><th>Meso</th><th class="num">Najmanje</th></tr>
    <tr><td>Piletina, puretina, patka — cijela, batak, prsa, mljevena</td><td class="num">74 °C</td></tr>
    <tr><td>Mljeveno meso (junetina, svinjetina, janjetina) — pljeskavice, ćevapi, polpete</td><td class="num">71 °C</td></tr>
    <tr><td>Junetina, teletina, janjetina — odresci, pečenje (cijeli komadi)</td><td class="num">63 °C + 3 min odmora</td></tr>
    <tr><td>Svinjetina — odresci, vrat, pečenje</td><td class="num">63 °C + 3 min odmora</td></tr>
    <tr><td>Riba</td><td class="num">63 °C</td></tr>
    <tr><td>Podgrijani ostaci i složenci</td><td class="num">74 °C</td></tr>
</table>
<p>
    Ove vrijednosti preporučuju agencije za sigurnost hrane. Kod mljevenog mesa i peradi bakterije su prisutne
    i <em>unutar</em> komada, pa ga treba pržiti do kraja. Kod cijelih komada junetine i svinjetine bakterije su
    uglavnom na površini, koja se ionako dobro zapeče, pa je sigurna i niža temperatura u sredini.
</p>

<div class="note">
    Svinjetina pečena na 63 °C iznutra je blago ružičasta i sočna — to je normalno i sigurno. Nekadašnja pravila o
    svinjetini „dok nije skroz siva" danas su prestroga i daju suho meso.
</div>

<h2>Junetina po ukusu</h2>
<p>Za cijele komade junetine (biftek, ramstek, rozbif) mnogi biraju stupanj pečenosti prema ukusu:</p>
<table class="t">
    <tr><th>Stupanj</th><th class="num">Unutarnja temperatura</th><th>Izgled</th></tr>
    <tr><td>Krvavo (rare)</td><td class="num">50–52 °C</td><td>crvena sredina, hladnija</td></tr>
    <tr><td>Srednje krvavo (medium rare)</td><td class="num">55–57 °C</td><td>tamnoružičasta, topla</td></tr>
    <tr><td>Srednje (medium)</td><td class="num">60–63 °C</td><td>ružičasta</td></tr>
    <tr><td>Dobro pečeno (well done)</td><td class="num">70 °C i više</td><td>siva do kraja</td></tr>
</table>
<p>
    Temperature ispod 63 °C stvar su osobnog izbora za cijele komade kvalitetne junetine — za mljeveno meso, djecu,
    trudnice, starije i osobe slabijeg imuniteta drži se sigurnih vrijednosti iz prve tablice.
</p>

<h2>Kako pravilno mjeriti</h2>
<ol>
    <li>Ubodi termometar u <strong>najdeblji dio</strong> mesa, u sredinu komada.</li>
    <li>Ne diraj kost, masnoću ni dno posude — one pokazuju krivu temperaturu.</li>
    <li>Kod cijele piletine mjeri u najdeblji dio buta, uz zglob, i u prsa.</li>
    <li>Kod pljeskavica i tanjih komada ubodi termometar sa strane, vodoravno.</li>
    <li>Pričekaj da se brojka ustali — digitalni termometri trebaju nekoliko sekundi.</li>
</ol>

<h2>Odmaranje mesa</h2>
<p>
    Nakon što izvadiš meso iz pećnice ili s roštilja, temperatura u sredini još raste nekoliko stupnjeva. Zato veće
    pečenje izvadi 2–3 °C prije ciljane temperature, pokrij ga folijom i ostavi da odmori 10–15 minuta (odreske
    3–5 minuta). Za to vrijeme sokovi se vrate u vlakna, pa meso pri rezanju ne pušta toliko tekućine.
</p>

<h2>Česte pogreške</h2>
<ul>
    <li><strong>Prosudba po boji</strong> — piletina može biti bijela, a nedovoljno pečena, i obrnuto.</li>
    <li><strong>Mjerenje na rubu</strong> — rub je uvijek topliji od sredine.</li>
    <li><strong>Ista temperatura za sve</strong> — perad i mljeveno meso trebaju više od cijelih komada.</li>
    <li><strong>Prerezivanje mesa odmah</strong> — bez odmora sok iscuri na dasku.</li>
</ul>
