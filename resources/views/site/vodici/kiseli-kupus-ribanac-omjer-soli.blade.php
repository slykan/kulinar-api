<p>
    Premalo soli i kupus omekša i lako se pokvari; previše soli i fermentacija je spora, a kupus preslan. Sol
    izvaži, ne mjeri žlicom — žlica soli može biti i 15 i 25 g (vidi <a href="/vodici/kuhinjske-mjere-zlica-salica-preracunavanje">kuhinjske mjere</a>).
    Mnogi koriste krupnu morsku ili kamenu sol bez dodataka.
</p>

<h2>Što ti treba</h2>
<ul>
    <li>čvrste, teške glavice kasnog bijelog kupusa,</li>
    <li>posuda: kamenica, keramička ili staklena posuda, ili plastična bačva za hranu (ne metalna, osim inoksa),</li>
    <li>tanjur ili daska koja stane u posudu, i uteg (staklenka s vodom, čisti kamen u vrećici),</li>
    <li>po želji: lovor, papar u zrnu, kim, nekoliko kriški jabuke ili hrena.</li>
</ul>

<h2>Postupak</h2>
<ol>
    <li>Kupusu skini vanjske listove (nekoliko sačuvaj), izreži kocen i naribaj ga na rezance debljine 1–2 mm.</li>
    <li>Izvaži naribani kupus i izračunaj sol.</li>
    <li>Kupus slaži u posudu u slojevima od 5–10 cm, svaki sloj posoli odgovarajućim dijelom soli i začinima i snažno nagnječi šakom ili drvenim batom, dok ne počne puštati sok.</li>
    <li>Kad je sve složeno, sok mora prekrivati kupus. Odozgo stavi cijele listove, pa tanjur ili dasku i uteg.</li>
    <li>Ako sutradan sok ne prekriva kupus, dolij salamuru od 20 g soli na 1 l prokuhane i ohlađene vode.</li>
</ol>

<h2>Fermentacija</h2>
<ul>
    <li><strong>Temperatura:</strong> idealno 18–22 °C. Na višoj temperaturi kupus brzo kiseli, ali omekša; ispod 15 °C fermentacija jako uspori.</li>
    <li><strong>Prvi tjedni:</strong> kupus pjeni i pušta mjehuriće. Svakih nekoliko dana skini pjenu i eventualnu bijelu kožicu s površine i operi tanjur i uteg.</li>
    <li><strong>Gotov je</strong> nakon 3–6 tjedana, kad je ugodno kiseo i hrskav, a pjenjenje prestane. Tada ga premjesti na hladnije mjesto (podrum, 0–10 °C).</li>
</ul>
<div class="warn">
    Bijela kožica na površini salamure česta je i nije opasna ako se redovito skida. Ružičasta, smeđa ili sluzava
    masa, plijesan u kupusu ili truo miris znak su da je nešto pošlo krivo — takav kupus se ne jede.
</div>

<h2>Česte pogreške</h2>
<ul>
    <li><strong>Kupus nije pod salamurom</strong> — dio iznad tekućine posmeđi i pljesnivi.</li>
    <li><strong>Pretoplo</strong> — kupus uz radijator omekša i dobije neugodan miris.</li>
    <li><strong>Sol „od oka"</strong> — izvaži i kupus i sol.</li>
    <li><strong>Mlad, rahli kupus</strong> — za kiseljenje se uzimaju čvrste, kasne glavice.</li>
</ul>

<h2>Što s kiselim kupusom</h2>
<p>
    Ribanac je odličan kao salata s uljem i paprikom, u varivu s grahom ili kobasicama, u podvarku i u
    zapečenom kupusu. Za cijele listove kiselog kupusa, kakvi trebaju za <a href="/recepti/sarma-od-kiselog-kupusa">sarmu</a>,
    kisele se cijele glavice u salamuri, a postupak traje dulje.
</p>

