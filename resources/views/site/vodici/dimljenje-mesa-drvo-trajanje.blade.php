<p>
    Dimi se s prekidima: vatra tinja nekoliko sati dnevno (najčešće ujutro i navečer), pa se pušnica ostavi da se prozrači. Dim ne smije
    biti gust i žut nego tanak i plavkast. Bolje je dimiti dulje i slabije nego kratko i jako.
</p>

<h2>Česte pogreške</h2>
<ul>
    <li><strong>Pretoplo</strong> — ako se meso zagrije iznad 25–30 °C, mast se topi i curi, a kobasice se mogu „ukuhati” i pokvariti iznutra.</li>
    <li><strong>Mokro meso u dimu</strong> — tamna, ljepljiva i gorka kora.</li>
    <li><strong>Pregust dim, plamen</strong> — čađa i gorak okus.</li>
    <li><strong>Previše dima</strong> — dim prekrije okus mesa. Tradicionalni slavonski kulen dimi se umjereno.</li>
</ul>

