<p>
    Dobra crijeva pola su posla kod kobasica. Danas ih većina kupuje gotova, očišćena i soljena, ali na kolinju se i dalje često čiste
    domaća. Ovdje je što za što služi, kako se pripremaju kupljena i kako se čiste domaća.
</p>

