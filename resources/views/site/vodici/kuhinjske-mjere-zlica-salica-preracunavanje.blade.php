<div class="note">
    Kod soli je razlika između „ravne" i „pune" žlice gotovo dvostruka. Za kobasice i turšiju zato je bolje
    vagati — ili koristiti <a href="/kalkulatori">kalkulatore</a> koji računaju u gramima.
</div>

<h2>Deka, kila i stare mjere</h2>
<ul>
    <li><strong>1 dkg (deka)</strong> = 10 g — „15 deka šećera" je 150 g.</li>
    <li><strong>1 kg</strong> = 100 dkg = 1000 g.</li>
    <li><strong>1 l</strong> = 10 dl = 1000 ml.</li>
</ul>

<h2>Kako preračunati recept</h2>
<p>Pravilo je jednostavno: izračunaj <strong>faktor</strong> i pomnoži njime svaki sastojak.</p>
<div class="note">faktor = željena količina ÷ količina u receptu</div>
<p>
    <strong>Primjer:</strong> recept je za 4 osobe, a kuhaš za 10. Faktor je 10 ÷ 4 = 2,5. Ako recept traži
    400 g mesa, trebaš 400 × 2,5 = 1000 g; ako traži 2 žlice brašna, trebaš 5 žlica.
</p>
<h3>Na što paziti kod velikih količina</h3>
<ul>
    <li><strong>Začini i sol</strong> — kod jako velikih količina dodaj malo manje od izračunatog, probaj i dosoli.</li>
    <li><strong>Vrijeme kuhanja</strong> ne raste s faktorom: dvostruka količina variva ne kuha se dvostruko dulje, ali treba dulje da zavrije.</li>
    <li><strong>Posuda</strong> — veća količina u istoj posudi peče se i prži drukčije; peci u više tura.</li>
    <li><strong>Jaja i komadi</strong> zaokruži na cijeli broj (2,5 jaja → 2 veća ili 3 manja).</li>
</ul>
<p>Kalkulatori na Kulinar.app rade upravo ovo — npr. <a href="/kalkulatori/tripice">kalkulator tripica</a> preračunava recept za 3 osobe na bilo koju količinu.</p>
