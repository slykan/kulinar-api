<h2>Prije kolinja</h2>
<ul>
    <li><strong>Vrijeme:</strong> kolinje se radi kad je hladno, idealno kad su dnevne temperature ispod 5 °C, a noću mrzne. Meso se mora dobro ohladiti preko noći.</li>
    <li><strong>Veterinarski pregled:</strong> meso svinje zaklane kod kuće mora pregledati veterinar (trihinela). Dogovori ga na vrijeme.</li>
    <li><strong>Nabavi unaprijed:</strong> sol i nitritnu sol, papriku, papar, češnjak, crijeva, rižu ili kašu za krvavice, staklenke za mast. Količine izračunaj u <a href="/kalkulatori/svinja">kalkulatoru koliko mesa daje svinja</a> i <a href="/kalkulatori/crijeva">kalkulatoru crijeva</a>.</li>
    <li><strong>Pripremi:</strong> stroj za mljevenje i punjenje, oštre noževe, stol, kotao, puno posuda i čiste krpe.</li>
</ul>

<h2>Redoslijed poslova na dan kolinja</h2>
<ol>
    <li><strong>Jutro:</strong> klanje, hvatanje krvi (uz stalno miješanje da se ne zgruša), šurenje ili paljenje dlake, vađenje iznutrica.</li>
    <li>Polovice se objese da se ohlade. U međuvremenu se peru crijeva i kuhaju glava, koža, jezik, srce i pluća za krvavice i švarglu.</li>
    <li><strong>Poslijepodne:</strong> rasijecanje ohlađenih polovica — butovi, lopatice, leđa, potrbušina, slanina.</li>
    <li>Topljenje masti i čvaraka u kotlu, dok se ostali bave krvavicama i švarglom.</li>
    <li>Kobasice se obično rade <strong>drugi dan</strong>, kad je meso potpuno ohlađeno, jer se onda lakše melje i bolje veže.</li>
</ol>

<h2>Krvavice</h2>
<p>
    Krvavice se rade od kuhanog mesa s glave, kože, pluća i masnijih obrezaka, pomiješanog s krvlju i rižom ili kašom. Svaka kuća ima
    svoj omjer, ali dobra je polazna točka ova: na <strong>1 litru krvi</strong> ide oko <strong>1 kg kuhanog mesa i kože</strong>,
    <strong>0,5 kg kuhane riže ili ječmene kaše</strong> i <strong>0,5 kg čvaraka ili kuhane slanine</strong>.
</p>
<ul>
    <li><strong>Začini na 3 kg smjese:</strong> 50–60 g soli, 10 g papra, 10 g mljevenog klinčića ili pimenta, 1 žličica mažurana, 1 glavica pirjanog luka. Po želji malo cimeta.</li>
    <li>Krv mora biti svježa i procijeđena. Ako nije odmah za upotrebu, drži je na hladnom i posoli (oko 10 g soli po litri).</li>
    <li>Smjesa se puni rijetka, u tanka crijeva, i <strong>ne do kraja</strong> jer se krvavice kuhanjem šire.</li>
    <li>Kuhaju se u vrućoj, ali ne kipućoj vodi (oko 80–85 °C) 20–30 minuta. Kad ih ubodeš iglom i izađe bistra mast, a ne krv, gotove su.</li>
    <li>Nakon kuhanja ohladi ih u hladnoj vodi i složi da se ne dodiruju. U hladnjaku traju 3–5 dana, a zamrznute nekoliko mjeseci.</li>
</ul>
