<h2>Klasični džem bez dodanog pektina</h2>
<p>
    Tradicionalni omjer je oko <strong>1 kg voća na 600–800 g šećera</strong>. Voće bogato pektinom (jabuke, dunje,
    ribiz, kisele šljive, agrumi) zgusne se samo; jagode, trešnje, breskve i marelice imaju malo pektina i trebaju
    dulje kuhanje ili dodatak.
</p>
<ol>
    <li>Voće očisti, nareži i pomiješaj sa šećerom. Ostavi ga sat-dva (ili preko noći u hladnjaku) da pusti sok.</li>
    <li>Kuhaj na jakoj vatri uz miješanje, skidajući pjenu, dok se ne zgusne — obično 20–40 minuta.</li>
    <li>Dodaj sok jednog limuna na 1 kg voća: kiselina pomaže želiranju i čuva boju.</li>
    <li>Napravi probu na hladnom tanjuru (vidi dolje) i, kad je gotov, odmah ga ulij u vruće sterilizirane staklenke.</li>
</ol>

<h2>Džem sa želirnim šećerom</h2>
<p>
    Želirni šećer sadrži pektin i kiselinu, pa se džem kuha samo nekoliko minuta i zadrži svježiji okus i boju.
    Na pakiranju piše omjer:
</p>
<table class="t">
    <tr><th>Oznaka</th><th class="num">Voće</th><th class="num">Šećer</th><th>Rezultat</th></tr>
    <tr><td>1:1</td><td class="num">1 kg</td><td class="num">1 kg</td><td>klasičan, najslađi</td></tr>
    <tr><td>2:1</td><td class="num">1 kg</td><td class="num">500 g</td><td>voćniji, manje sladak</td></tr>
    <tr><td>3:1</td><td class="num">1,5 kg</td><td class="num">500 g</td><td>najmanje šećera, kraće traje otvoren</td></tr>
</table>
<p>
    Drži se vremena kuhanja s pakiranja (najčešće 3–4 minute snažnog vrenja). Predugo kuhanje može razgraditi
    pektin, pa se džem ne zgusne.
</p>

<h2>Pekmez od šljiva</h2>
<ol>
    <li>Uzmi zrele, slatke šljive (bistrica, požegača) i ukloni koštice.</li>
    <li>Kuhaj ih u širokoj posudi s debelim dnom na laganoj vatri, uz često miješanje, da ne zagore. Neki ih prvu noć ostave u pećnici na 150–160 °C.</li>
    <li>Kuhanje traje nekoliko sati, dok masa ne potamni i ne postane toliko gusta da kuhača ostavlja trag na dnu.</li>
    <li>Šećer je neobavezan — zrele šljive su dovoljno slatke. Može se dodati malo cimeta ili klinčića.</li>
</ol>

<h2>Proba na hladnom tanjuru</h2>
<p>
    Prije kuhanja stavi tanjurić u zamrzivač. Kad misliš da je džem gotov, kapni malo na hladni tanjur i vrati ga u
    zamrzivač na minutu. Ako se površina nabora kad je pogurneš prstom, džem je gotov; ako se razlije, kuhaj još.
</p>

<h2>Koliko traje</h2>
<ul>
    <li>Džem s dovoljno šećera (1:1 i klasični), dobro zatvoren i pasteriziran, traje oko godinu dana.</li>
    <li>Džem s manje šećera (2:1, 3:1) i otvorena staklenka čuvaju se u hladnjaku i treba ih potrošiti brže.</li>
    <li>Ako se na površini pojavi plijesan, baci cijelu staklenku — ne samo površinski sloj.</li>
</ul>
<p>
    Pripremu staklenki i pasterizaciju objašnjava vodič <a href="/vodici/zimnica-sterilizacija-pasterizacija-staklenki">zimnica: sterilizacija i pasterizacija staklenki</a>,
